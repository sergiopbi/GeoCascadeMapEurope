import csv, glob, os, re, json, sys
CAP = int(sys.argv[1]) if len(sys.argv) > 1 else 12000
out = {}
total = 0
rep = []
for f in sorted(glob.glob(os.path.expanduser('~/zauberware/postal-codes-json-xml-csv/data/x/*/*.csv'))):
    rows = []
    with open(f, encoding='utf-8') as fh:
        for r in csv.DictReader(fh):
            try:
                lat = float(r['latitude']); lon = float(r['longitude'])
            except Exception:
                continue
            code = re.sub(r'[^0-9A-Z]', '', (r['zipcode'] or '').upper())
            if code:
                rows.append((code, lon, lat))
    if not rows:
        continue
    cc = rows[0] and os.path.basename(os.path.dirname(f))
    from collections import Counter
    maxlen = max(len(c) for c, _, _ in rows)
    L = Counter(len(c) for c, _, _ in rows).most_common(1)[0][0]
    while L > 1:
        uniq = len(set(c[:L] for c, _, _ in rows))
        if uniq <= CAP:
            break
        L -= 1
    agg = {}
    for c, lon, lat in rows:
        k = c[:L]
        a = agg.setdefault(k, [0.0, 0.0, 0])
        a[0] += lon; a[1] += lat; a[2] += 1
    s = ';'.join(f"{k}|{a[0]/a[2]:.2f}|{a[1]/a[2]:.2f}" for k, a in sorted(agg.items()))
    M = Counter(len(c) for c, _, _ in rows).most_common(1)[0][0]
    out[cc] = {'L': L, 'M': M, 'd': s}
    total += len(s)
    rep.append(f"{cc}:{L}/{maxlen}:{len(agg)}")
print('countries', len(out), 'bytes', total)
print(' '.join(rep))
dst = sys.argv[2] if len(sys.argv) > 2 else None
if dst:
    with open(dst, 'w', encoding='utf-8') as fh:
        fh.write('/* Generated by buildpostal.py — do not edit. */\n')
        fh.write('/* Postal codes: GeoNames postal code data (CC BY 4.0) via zauberware/postal-codes-json-xml-csv, aggregated to prefix length L per country (centroid of all codes sharing the prefix). */\n')
        fh.write('// per ISO2: { L: prefix length used, M: usual full code length, d: "CODE|lon|lat;..." } — codes normalised to [0-9A-Z] only\n')
        fh.write('export const POSTAL: { [cc: string]: { L: number; M: number; d: string } } = ' + json.dumps(out, ensure_ascii=False) + ';\n')
